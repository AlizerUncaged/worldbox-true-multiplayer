"""Bake the build-time .env into generated C# constants.

Usage: python bake_env.py <path-to-.env> <output.g.cs>

Reads KEY=VALUE lines ('#' comments) and emits WorldboxMP.Client.BuildConfig.
Kept as a script (not inline MSBuild) for the same reason as stamp_version.py:
cmd.exe mangles inline one-liners silently.
"""
import io
import sys

env_path, out_path = sys.argv[1], sys.argv[2]

values = {}
for raw in io.open(env_path, encoding="utf-8"):
    line = raw.strip()
    if not line or line.startswith("#") or "=" not in line:
        continue
    k, v = line.split("=", 1)
    values[k.strip()] = v.strip()

source = values.get("MAIN_SERVER_SOURCE", "")
if not source:
    sys.exit("bake_env: MAIN_SERVER_SOURCE missing in " + env_path)


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


code = """// <auto-generated>
// Generated by bake_env.py from src/Client/.env at build time. Do not edit;
// change .env instead. Never ships as a file - values live in the assembly.
// </auto-generated>
namespace WorldboxMP.Client
{
    public static class BuildConfig
    {
        /// <summary>The official server origin baked at build time (scheme decides
        /// the shared TCP+UDP port: https=443, http=80, explicit :port wins).</summary>
        public const string MainServerSource = "%s";
    }
}
""" % esc(source)

io.open(out_path, "w", encoding="utf-8").write(code)
print("bake_env: %s -> %s" % (source, out_path))
